"""The ComfyUI workflow library Conversar's bot runs from: data/workflows.json, a list of
{id, name, description, workflow (API format), created_at, updated_at}.

Seeded once, when the file doesn't exist, from app/seed_workflows/ (the owner's own
workflows, taken from image-generation); edited in Ajustes, and the bot can save the
versions it modifies. Names are unique, case-insensitively: the bot refers to workflows
by name.
"""
import json
import uuid
from datetime import datetime, timezone
from pathlib import Path

from . import storage
from .comfy_graph import is_api_workflow
from .config import get_settings

SEED_DIR = Path(__file__).parent / "seed_workflows"
MAX_NAME_LENGTH = 80


class WorkflowError(ValueError):
    pass


def _default_path() -> str:
    return f"{get_settings().data_dir}/workflows.json"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def ensure_seeded(path: str | None = None) -> None:
    resolved_path = path or _default_path()
    if Path(resolved_path).exists():
        return
    index = json.loads((SEED_DIR / "index.json").read_text(encoding="utf-8"))
    now = _now()
    entries = [
        {
            "id": str(uuid.uuid4()),
            "name": item["name"],
            "description": item["description"],
            "workflow": json.loads((SEED_DIR / item["file"]).read_text(encoding="utf-8")),
            "created_at": now,
            "updated_at": now,
        }
        for item in index
    ]
    storage.write_json(resolved_path, entries)


def list_workflows(path: str | None = None) -> list[dict]:
    return storage.read_json(path or _default_path(), default=[])


def summaries(path: str | None = None) -> list[dict]:
    return [
        {k: w[k] for k in ("id", "name", "description", "updated_at")} | {"node_count": len(w["workflow"])}
        for w in list_workflows(path)
    ]


def get(workflow_id: str, path: str | None = None) -> dict | None:
    return next((w for w in list_workflows(path) if w["id"] == workflow_id), None)


def find_by_name(name: str, path: str | None = None) -> dict | None:
    key = (name or "").strip().casefold()
    return next((w for w in list_workflows(path) if w["name"].casefold() == key), None)


def _validated(name: str, description: str, workflow, entries: list[dict], own_id: str | None) -> tuple[str, str]:
    name = " ".join((name or "").split())
    if not name:
        raise WorkflowError("A workflow needs a name")
    if len(name) > MAX_NAME_LENGTH:
        raise WorkflowError(f"Workflow names are at most {MAX_NAME_LENGTH} characters")
    if any(w["name"].casefold() == name.casefold() and w["id"] != own_id for w in entries):
        raise WorkflowError(f"There is already a workflow named {name}")
    if not is_api_workflow(workflow):
        raise WorkflowError(
            "That isn't an API-format workflow: in ComfyUI use Workflow > Export (API), "
            "or import an image generated by ComfyUI"
        )
    return name, (description or "").strip()


def create(name: str, description: str, workflow: dict, path: str | None = None) -> dict:
    resolved_path = path or _default_path()
    entries = list_workflows(resolved_path)
    name, description = _validated(name, description, workflow, entries, None)
    now = _now()
    entry = {"id": str(uuid.uuid4()), "name": name, "description": description,
             "workflow": workflow, "created_at": now, "updated_at": now}
    entries.append(entry)
    storage.write_json(resolved_path, entries)
    return entry


def update(workflow_id: str, name: str, description: str, workflow: dict, path: str | None = None) -> dict | None:
    resolved_path = path or _default_path()
    entries = list_workflows(resolved_path)
    entry = next((w for w in entries if w["id"] == workflow_id), None)
    if entry is None:
        return None
    name, description = _validated(name, description, workflow, entries, workflow_id)
    entry.update(name=name, description=description, workflow=workflow, updated_at=_now())
    storage.write_json(resolved_path, entries)
    return entry


def delete(workflow_id: str, path: str | None = None) -> bool:
    resolved_path = path or _default_path()
    entries = list_workflows(resolved_path)
    remaining = [w for w in entries if w["id"] != workflow_id]
    if len(remaining) == len(entries):
        return False
    storage.write_json(resolved_path, remaining)
    return True
